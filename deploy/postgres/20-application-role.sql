\set ON_ERROR_STOP on
\getenv application_password BOARDSAFE_APP_DB_PASSWORD
CREATE ROLE boardsafe_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD :'application_password';
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT CONNECT ON DATABASE boardsafe TO boardsafe_app;
GRANT USAGE ON SCHEMA public TO boardsafe_app;
ALTER DEFAULT PRIVILEGES FOR ROLE boardsafe_owner IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO boardsafe_app;
ALTER DEFAULT PRIVILEGES FOR ROLE boardsafe_owner IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO boardsafe_app;
